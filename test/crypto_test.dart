@Timeout(Duration(minutes: 3))
library;

import 'dart:convert';
import 'dart:io';
import 'dart:typed_data';

import 'package:flutter_test/flutter_test.dart';
import 'package:haam_remote/src/crypto/der.dart';
import 'package:haam_remote/src/crypto/identity.dart';

String _hex(List<int> bytes) => bytes.map((b) => b.toRadixString(16).padLeft(2, '0')).join();

void main() {
  group('DER', () {
    test('encodes integers with a sign byte only when needed', () {
      expect(Der.integer(BigInt.zero), [0x02, 0x01, 0x00]);
      expect(Der.integer(BigInt.from(127)), [0x02, 0x01, 0x7F]);
      expect(Der.integer(BigInt.from(128)), [0x02, 0x02, 0x00, 0x80]);
      expect(Der.integer(BigInt.from(65537)), [0x02, 0x03, 0x01, 0x00, 0x01]);
      expect(Der.integer(BigInt.from(-129)), [0x02, 0x02, 0xFF, 0x7F]);
    });

    test('encodes OIDs', () {
      expect(_hex(Der.oid('1.2.840.113549.1.1.11')), '06092a864886f70d01010b');
      expect(_hex(Der.oid('2.5.29.19')), '0603551d13');
    });

    test('uses long-form lengths', () {
      final long = Der.octetString(List<int>.filled(300, 1));
      expect(long.sublist(0, 4), [0x04, 0x82, 0x01, 0x2C]);
      expect(DerNode.parse(long).content.length, 300);
    });

    test('switches to GeneralizedTime from 2050', () {
      expect(utf8.decode(Der.time(DateTime.utc(2049, 12, 31, 23, 59, 59)).sublist(2)), '491231235959Z');
      final g = Der.time(DateTime.utc(2056, 1, 2, 3, 4, 5));
      expect(g[0], Der.tagGeneralizedTime);
      expect(utf8.decode(g.sublist(2)), '20560102030405Z');
    });
  });

  group('pairing vectors (generated by tool/mock_tv/gen_vectors.py)', () {
    final json = jsonDecode(File('test/fixtures/pairing_vectors.json').readAsStringSync()) as Map<String, dynamic>;
    final vectors = (json['vectors'] as List<dynamic>).cast<Map<String, dynamic>>();

    for (final v in vectors) {
      group(v['label'] as String, () {
        final clientPublic = rsaPublicKeyFromCertificate(pemToDer(v['client_cert_pem'] as String));
        final serverDer = hexToBytes(v['server_cert_der_hex'] as String);
        final serverPublic = rsaPublicKeyFromCertificate(serverDer);

        test('reads RSA numbers from certificates', () {
          expect(clientPublic.modulus, BigInt.parse(v['client_modulus_hex'] as String, radix: 16));
          expect(clientPublic.exponent, BigInt.from(v['client_exponent'] as int));
          expect(serverPublic.modulus, BigInt.parse(v['server_modulus_hex'] as String, radix: 16));
          expect(serverPublic.exponent, BigInt.from(v['server_exponent'] as int));
          expect(sha256Hex(serverDer), v['server_sha256']);
        });

        test('computes the secret the TV expects', () {
          final secret = pairingSecret(client: clientPublic, server: serverPublic, code: v['code'] as String);
          expect(secret, isNotNull);
          expect(_hex(secret!), v['secret_hex']);
          final lower = pairingSecret(
            client: clientPublic,
            server: serverPublic,
            code: (v['code'] as String).toLowerCase(),
          );
          expect(lower, secret);
        });

        test('detects a mistyped code before sending it', () {
          final code = v['code'] as String;
          final first = (int.parse(code.substring(0, 2), radix: 16) + 1) % 256;
          final wrongFirst = '${first.toRadixString(16).padLeft(2, '0')}${code.substring(2)}';
          expect(pairingSecret(client: clientPublic, server: serverPublic, code: wrongFirst), isNull);
          expect(pairingSecret(client: clientPublic, server: serverPublic, code: 'GG0000'), isNull);
          expect(pairingSecret(client: clientPublic, server: serverPublic, code: '12345'), isNull);
        });
      });
    }
  });

  group('generated identity', () {
    late ClientIdentity identity;
    late Directory dir;

    setUpAll(() {
      identity = ClientIdentity.generate();
      dir = Directory.systemTemp.createTempSync('haam_identity');
      File('${dir.path}/cert.pem').writeAsStringSync(identity.certificatePem);
      File('${dir.path}/key.pem').writeAsStringSync(identity.privateKeyPem);
    });

    tearDownAll(() => dir.deleteSync(recursive: true));

    test('is a 2048-bit key with exponent 65537', () {
      expect(identity.publicKey.modulus.bitLength, 2048);
      expect(identity.publicKey.exponent, BigInt.from(65537));
    });

    test('survives a PEM round trip', () {
      final again = ClientIdentity(certificatePem: identity.certificatePem, privateKeyPem: identity.privateKeyPem);
      expect(again.publicKey.modulus, identity.publicKey.modulus);
    });

    test('is accepted by Dart TLS as a client certificate', () {
      expect(
        () => SecurityContext(withTrustedRoots: false)
          ..useCertificateChainBytes(utf8.encode(identity.certificatePem))
          ..usePrivateKeyBytes(utf8.encode(identity.privateKeyPem)),
        returnsNormally,
      );
    });

    test('is a valid self-signed certificate whose key matches (OpenSSL)', () async {
      final ProcessResult verify;
      try {
        verify = await Process.run('openssl', [
          'verify',
          '-CAfile',
          '${dir.path}/cert.pem',
          '${dir.path}/cert.pem',
        ]);
      } on ProcessException {
        markTestSkipped('openssl is not installed');
        return;
      }
      expect(verify.exitCode, 0, reason: '${verify.stdout}${verify.stderr}');
      final certMod = await Process.run('openssl', ['x509', '-noout', '-modulus', '-in', '${dir.path}/cert.pem']);
      final keyMod = await Process.run('openssl', ['rsa', '-noout', '-modulus', '-in', '${dir.path}/key.pem']);
      expect(keyMod.exitCode, 0, reason: '${keyMod.stderr}');
      expect(certMod.stdout, keyMod.stdout);
      final check = await Process.run('openssl', ['rsa', '-check', '-noout', '-in', '${dir.path}/key.pem']);
      expect(check.exitCode, 0, reason: '${check.stdout}${check.stderr}');
    });
  });

  test('hexToBytes pads odd input', () {
    expect(hexToBytes('abc'), Uint8List.fromList([0x0A, 0xBC]));
  });
}
